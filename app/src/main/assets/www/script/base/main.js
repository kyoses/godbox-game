	//播放帧动画
	playAnimation:function(id,array,index,infinite,callBack,args){
		index=(index==undefined?0:index);
		infinite=(infinite==undefined?0:infinite);//一直播或只播放一次
		var obj=$("#"+id);
		if(obj.length<=0 || obj.css("display")=="none"){
			return;
		}
		var nowUrl="";
		var nextFrameTime=200;
		if(infinite==1 && index>=array.length){
			if(callBack){
				callBack(args);
			}
			return;
		}
		if(index>=array.length){
			index=0;
		}
		if(typeof array[index]=="object"){
			if(array[index].nextT!=undefined){
				nextFrameTime=array[index].nextT;
			}
			nowUrl=array[index].url;
			
		}
		else{
			nowUrl=array[index];
		}
		obj.attr("src",nowUrl);
		if(array[index].callBack){
			for(key in array[index].callBack){
				array[index].callBack[key]();
			}
		}
		setTimeout(mainPage.playAnimation,nextFrameTime,id,array,++index,infinite,callBack,args);
	},
